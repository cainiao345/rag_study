# build_index.py —— 研报问答库的「索引侧」：把资料变成可检索的向量库
#
# 【这张脚本到底要干什么 · 一句话】
#   data/ 里的 txt/pdf → 逐页读 → 按句切块 → 调 API 变向量 → 连出处卡片
#   一起存进本地 chroma_db/，供第 9 课（下）的问答侧检索。
#
# 【流水线地图 · 记住这 5 步，下面每个函数都只是其中一步】
#   ① 解析   load_pages()        ：一份资料 → 一页一条（页码在这一步保住）
#   ② 分块   chunk_pages()      ：一页一条 → 一块一条 + 每块配一张出处卡片
