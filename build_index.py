# 流水线 ③：批量向量化 —— 本课两个「最阴的坑」之一在这里
# ============================================================================
def embed_batch(texts, client, batch_size=32):
    # 【目标】把 N 块文字变成 N 条向量，且 vectors[i] 必须就是 texts[i] 的向量。
    # 【输入】texts = 原文块列表；client = 向量化客户端；batch_size = 每批最多几条
    # 【输出】vectors = 向量列表，长度与顺序都与 texts 完全一致
    # 【为什么不全量一次发】免费档有 RPM/TPM 限流，几百条一次塞过去容易被 429 拒。
    # 【为什么不一条条发】每条一次网络往返，几百条要几分钟，还更容易撞限流。
    # 【本函数最大的风险】API 批量返回「不保证顺序」，处理错就是静默错位（见下面 slots）。

    vectors = []
    # 做什么：空列表，装最终的全部向量。
    # 为什么：结果必须按 texts 的原顺序排队，所以用有序列表，不用字典或集合。

    for start in range(0, len(texts), batch_size):
        # 做什么：算出每一批的「起始下标」。
        # 为什么：range(起点, 终点, 步长) 第三个参数是步长，所以 start 依次是
        #         0、32、64、96…（不是 0、1、2、3）；步长正好等于每批条数，
        #         下一批才接在上一批屁股后面，不重叠也不漏。
        # 【举例】共 70 条、batch_size=32 → start = 0 / 32 / 64，三批分别是 32 + 32 + 6 条。
        # 【反例】若写成 0:32、1:33、2:34…，第 1 条文字会被重复送 32 次，
        #         重复烧额度、重复进库，还把「块」的边界彻底搞乱。

        batch = texts[start:start + batch_size]
        # 做什么：切片取出这一批；例如 start=32 时取 texts[32:64]（含 32、不含 64）。
        # 为什么：Python 切片超出右边界会自动截断且不报错，所以最后一批只剩 6 条也不用特判。
        # 语法：[起:止] 是「左闭右开」，长度 = 止 - 起（没超界时）。

        r = client.embeddings.create(
            # 做什么：调 /embeddings 端点；r 是服务端回的整个包裹。
            model=EMBED_MODEL,
            # 做什么：指定用哪个模型算向量。
            # 为什么：建库和提问必须同一个模型（第 2/5/6 课），用常量逼两边一致。
            input=batch,
            # 做什么：一次把这批的 32 条文字全交上去——传「列表」就是批量请求。
            # 为什么：一次网络往返算 32 条，比 32 次往返快得多，也更不容易撞限流。
        )

        slots = [None] * len(batch)
        # 做什么：先造一排空格子，格子数 = 这批的条数；
        #         下标 0/1/2… 就代表 batch 的第 0/1/2… 条。
        # 为什么：先按「原顺序」把坑位占好，等会儿不管结果怎么乱着回来，都能对号入座。
        # 语法：[None] * n 是列表乘法，把 None 重复 n 次；None 在这里表示「这个坑还空着」。

        for item in r.data:
            # 做什么：一条条取出结果对象，不看 item 排在第几位。
            # 为什么：OpenAI 兼容接口不保证 r.data[k] 对应 batch[k]——
            #         服务端并行算，谁先算完谁先回，返回顺序可能打乱。

            slots[item.index] = item.embedding
            # 做什么：把这条向量放进「它自己报的编号」那个格子。
            #   item.index     = 服务端标明的「我是 input 里的第几条」（回家的门牌号）
            #   item.embedding = 这条例对应的 1024 个数字（货物本身）
            # 为什么：这是全篇最关键的一行。按编号回填，返回顺序再乱也自动归位；
            #   若偷懒写 [x.embedding for x in r.data]，就是按「回来的顺序」硬排，
            #   第 3 块的向量会被配给第 1 块原文 → 入库不报错、检索全乱。
            # 【同一张错位表有两种问法，别绕晕】仍以 batch=[甲,乙,丙]、返回 [V丙,V甲,V乙] 为例：
            #   从「原文 → 向量」看：甲(现金流) 拿到的确实是 V丙(风险提示)；
            #   从「向量 → 原文」看：甲自己的向量 V甲 被挂到了乙(营收增长)那条原文上。
            #   两句说的是同一件事，而真正让检索坏掉的是后一句：
            #   问「现金流多少」→ 最像 V甲 → V甲 在下标 1 → 取回 documents[1] = 营收增长。
            #   错位是整张表转了一圈，不是只错一对；三种原文各自都配错了，只是危害看哪一行。
            # ⚠️ 为什么叫「最阴的静默错误」：条数对、维度对、类型全对，
            #   Chroma 照单全收，建库日志全是绿的；只有问答时答案张冠李戴，
            #   而且按第 8 课「先看料」也查不出来——原文是对的，错的是原文↔向量的绑定，
            #   肉眼看不见。唯一解法是重建索引。
            # 【进阶防呆】填完可以检查 if None in slots: raise ...，
            #   防「服务端少回一条」导致某个格子永远空着；本讲先不加，保持链路简单。

        vectors.extend(slots)
        # 做什么：把这一批格子「逐个」接到总列表末尾。
        # 为什么：extend 是拆开逐个加；append 会把整批当成一个元素塞进去，多套一层列表。
        #         批次内部已归位、批次之间按 start 递增拼接，所以最终 vectors[i] ↔ texts[i]。

    return vectors
    # 做什么：返回与 texts 等长、顺序一致的向量列表。


# ============================================================================
# 总装线：把 ①~⑤ 串起来 —— 本课另一个重点（幂等重建 + 四列防呆）在这里
# ============================================================================
def build_index(paths, client=None):
    # 【目标】从「一堆资料路径」到「一个可直接检索的集合」。
    # 【输入】paths = 资料路径列表；client 可选，不传就自己造（传是为了以后写测试换假客户端）
    # 【输出】(col, chunks, metas, vectors)：集合对象 + 三列数据，后三样给 main() 打印统计和自测
    # 【设计原则】任何一步发现脏数据，立刻 raise 停掉，绝不把坏库写进磁盘——
    #   写进去就污染了，之后每次检索都错，还很难查。

    if client is None:
        # 做什么：判断调用者有没有传客户端进来。

        client = make_embed_client()
        # 做什么：没传就自己造一个（内部会先跑配置自检）。
        # 为什么：把「造客户端」做成可替换的入口，测试时不花真 API 额度。

    chunks = []
    # 做什么：空列表，装所有文件的原文块（第 1 列）。
    metas = []
    # 做什么：空列表，装所有块对应的出处卡片（第 3 列）。
    # 为什么：两者从头到尾同步追加，是后面「四列对齐」的前提。

    for path in paths:
        # 做什么：一份一份资料处理。

        pages = load_pages(path)
        # ① 做什么：解析，资料 → 一页一条（页码在这一步留住）。

        c, m = chunk_pages(pages)
        # ② 做什么：分块，一页一条 → 一块一条 + 出处卡片（一次返回两个值，这里拆包）。

        chunks.extend(c)
        # 做什么：把这份资料的块接进总列表。
        # 为什么：extend 拆开逐个加；append 会把整份资料的块列表当成一个元素塞进来。

        metas.extend(m)
        # 做什么：卡片同步 extend。
        # 为什么：和 chunks 用完全相同的操作，保证第 n 块仍对应第 n 张卡。

    if not chunks:
        # 做什么：空列表算「假」→ 一份资料都没解析出内容。

        raise RuntimeError("没有解析出任何文本块，请检查 data/ 目录里的资料")
        # 做什么：主动报错，并在报错里说清去哪儿放资料。
        # 为什么：继续跑会建出一个空库，还打印「建库完成 ✅」，比直接报错更坑。

    vectors = embed_batch(chunks, client)
    # ③ 做什么：批量把每块文字变成 1024 个数字，顺序与 chunks 一致。

    # ── 防呆 A：四列对齐验票 ─────────────────────────────────────────────
    if not (len(chunks) == len(metas) == len(vectors)):
        # 做什么：验票——三个列表长度必须一模一样。
        # 为什么：下面 col.add 是「按位置配对」的四列表格，第 n 行的
        #   ids[n] / documents[n] / embeddings[n] / metadatas[n] 属于同一条记录。
        #   只要有一列少一条，后面全部往前串一位：原文配到别人的向量、别人的页码，
        #   又是一次不报错的静默错位（和 ③ 的 item.index 是同一类坑）。
        # 这就是「防呆」：宁可现在红字停，也不能把错位的库写进磁盘。
        # 语法：a == b == c 是链式比较，等价于 a==b 且 b==c；
        #       not (...) 把「全相等」取反 → 「只要不全相等就进来」。

        raise RuntimeError("chunks / metadatas / embeddings 长度不一致，禁止入库")
        # 做什么：抛异常终止，一行数据都不写。
        # 为什么：错误信息直接点名是哪三列出问题，看一眼就知道回哪儿查。

    db = chromadb.PersistentClient(path=DB_PATH)
    # ④ 做什么：打开（没有就创建）磁盘上的向量库，返回库对象 db。
    # 为什么：PersistentClient 会落盘，脚本关了再开数据还在；
    #         EphemeralClient 是纯内存，程序一退全没，不能用来建库。

    # ── 防呆 B：幂等重建 —— 让脚本跑 1 次和跑 100 次结果一样 ────────────
    try:
        # 做什么：试着删旧集合——这一步「可能失败」，所以要包 try。
        db.delete_collection(COLLECTION_NAME)
        # 做什么：把名为 "reports" 的整张表连同里面所有记录一起删掉。
        # 为什么必须删（不删会怎样）：
        #   ① ids 是 c0/c1/c2 固定生成，第二次 add 同样的 id → Chroma 报重复 id；
        #   ② 就算换成随机 id，库里会变成 6 条，同一段原文存两遍，
        #      检索时重复料进 prompt，答案啰嗦甚至互相矛盾；
        #   ③ 更要命：第 8 课改过分块策略，旧库里还留着「旧切法」的块，
        #      你改了代码答案却不变——第 8 课才强调「改完必须重建索引」。
        # 「幂等」= 跑 1 次和跑 100 次结果一样：库里永远只有「当前这版代码」切出来的块。
    except NotFoundError:
        # 做什么：只接住「集合不存在」这一种异常。
        # 为什么：第一次跑（或刚删过）根本没有旧集合，删它会抛 NotFoundError，
        #         这属于正常情况不是故障；只接它，别把网络错、权限错也一起吞掉。

        pass
        # 做什么：什么都不做，继续往下走。
        # 为什么：没旧集合本来就不用删。pass 在这儿是「明确宣告无需补救」，
        #         不是偷懒省略——Python 不允许空的代码块，必须有一句占位。

    col = db.get_or_create_collection(
        # 做什么：拿到（或在删掉后新建）集合，相当于数据库里的一张表。
        # 为什么：用 get_or_create 而不是 create，第一次跑和重复跑都不会因「已存在/不存在」报错。
        name=COLLECTION_NAME,
        # 做什么：指定表名。
        # 为什么：必须和上面 delete 的是同一个名字，否则等于删了 A 表又建 B 表。
        metadata={"hnsw:space": "cosine"},
        # 做什么：建表时指定「用余弦距离算相似度」。
        # 为什么：Chroma 默认 l2（欧氏距离），而 embedding 比的是方向（第 2 课），
        #         余弦才对；这是「建表参数」，删表时会一起没掉，所以每次重建都得重新带上。
    )

    # ── ⑤ 入库：四列按位置对齐，像一张四列的表格 ─────────────────────────
    col.add(
        # 做什么：一次把全部记录写进集合。
        ids=[f"c{i}" for i in range(len(chunks))],
        # 做什么：按块数现场造唯一编号 c0、c1、c2…（列表推导式 + f-string）。
        # 为什么：每条记录必须有不重复的主键，以后才能按 id 更新/删除；
        #         用 len(chunks) 生成，长度天然等于块数，所以上面只需验另外三列。
        documents=chunks,
        # 做什么：第 1 列 = 原文，检索命中时给人看、拼进 prompt。
        embeddings=vectors,
        # 做什么：第 2 列 = 1024 维向量，算「像不像」全靠它。
        metadatas=metas,
        # 做什么：第 3 列 = 出处卡片（文件名 + 页码），答案溯源全靠它。
        # 为什么：值只能是 str/int 等单个值，不能塞列表或字典（Chroma 的限制）。
        # 【四列怎么绑】c0 ↔ chunks[0] ↔ vectors[0] ↔ metas[0] 是同一行；
        #   上面那个长度校验，就是在保证这四列能严丝合缝地对齐。
    )

    return col, chunks, metas, vectors
    # 做什么：一次返回四样东西：集合对象、块、卡片、向量。
    # 为什么：main() 要拿它们打印统计、抽查出处卡、做检索自测，省得再查一次库。


# ============================================================================
# 总指挥：找资料 → 调总装线 → 打印结果做肉眼验收
# ============================================================================
def main():
    # 【目标】脚本入口，按顺序把上面的流程跑一遍，并把结果打印出来给人看。
    # 【为什么把 main 单独放】下面有 if __name__ == "__main__" 保护，
    #   别的文件 import 本模块时不会自动建库、不会偷偷花 API 额度。

    paths = sorted(DATA_DIR.glob("*.txt")) + sorted(DATA_DIR.glob("*.pdf"))
    # 做什么：glob("*.txt") 按通配符找出目录下所有 txt，两个列表用 + 拼起来（先 txt 后 pdf）。
    # 为什么：sorted 排序让每次运行的文件顺序一致，切块顺序、id 编号才可复现；
    #         否则同一份资料两次跑出来的 c0 指向不同内容，排查时很迷惑。

    if not paths:
        # 做什么：一份资料都没找到。

        raise RuntimeError(f"{DATA_DIR} 里没有 txt 或 pdf，请先放一份研报进去")
        # 做什么：主动报错，并说清该去哪儿放资料。
        # 为什么：别让后面报一个含糊的「0 块」。

    print(f"找到 {len(paths)} 份资料：{[p.name for p in paths]}")
    # 做什么：打印文件名清单。
    # 为什么：肉眼先确认「扫描对了」，再看后面的统计；排障时先看输入对不对。

    col, chunks, metas, vectors = build_index(paths)
    # 做什么：一条流水线跑完，拿到集合对象和三列数据（这里拆包成四个变量）。

    print(f"建库完成：{len(chunks)} 块，每块向量 {len(vectors[0])} 维")
    # 做什么：vectors[0] 是第一条向量，len() 数出它的维度（应为 1024）。
    # 为什么：维度不对就说明模型/接口不对，比等到检索时才发现便宜得多。

    print(f"集合 {COLLECTION_NAME} 现有 {col.count()} 条记录")
    # 做什么：col.count() 是 Chroma 提供的计数方法。
    # 为什么：这是「幂等」的验收点——重复跑脚本，这个数字不应该翻倍。

    print("\n--- 出处卡片抽查（前 3 块）---")
    # 做什么："\n" 是换行符，打印前先空一行，输出更好读。

    for c, m in list(zip(chunks, metas))[:3]:
        # 做什么：zip 把块和卡片拉链式配对，list(...) 转成列表后 [:3] 只取前 3 对。
        # 为什么：肉眼确认「第 n 块 ↔ 第 n 张卡」没有串位，是溯源最容易验的一步。

        print(f"  {m['source']} 第{m['page']}页｜{len(c)}字｜{c[:28]}…")
        # 做什么：打印文件名、页码、字数、原文前 28 字。
        # 为什么：引号要错开——外层双引号、里面字典取值用单引号（第 7 课踩过 SyntaxError）；
        #         {dist:.4f} 那种格式化里的 : 是「格式说明」，这里是普通取值，别混。

    print("\n--- 检索自测：用第 2 块的向量当问题，看能否连书带卡取回 ---")
    # 做什么：打印自测标题。

    res = col.query(
        # 做什么：检索，Chroma 内部算距离，返回最像的几块。
        # 为什么：拿「已有的向量」当 query，就不用再花一次 API 调用去向量化问题。
        query_embeddings=[vectors[1]],
        # 做什么：传「问题向量」；外面这层 [] 是 Chroma 的规矩（它设计成能一次查多个问题）。
        # 为什么：这里只传向量、不传问题原文，两种查询方式不要混用。
        n_results=2,
        # 做什么：只取最像的 2 块。
        include=["documents", "metadatas", "distances"],
        # 做什么：明确说要哪几列回来。
        # 为什么：不写 metadatas 就拿不到出处卡片，溯源会断（第 7 课的坑）。
    )

    for doc, meta, dist in zip(
        # 做什么：三列拉链式配对，一轮给出 (原文, 卡片, 距离)。
        res["documents"][0],
        # 做什么：[0] 取「第 1 个查询」的结果（返回值是列表的列表，外层按查询分组）。
        res["metadatas"][0],
        res["distances"][0],
    ):
        print(f"  距离 {dist:.4f}｜{meta['source']} 第{meta['page']}页｜{doc[:28]}…")
        # 做什么：打印距离、出处、原文开头。
        # 为什么：{dist:.4f} 让小数只显示 4 位；余弦距离越小越像，
        #         自测时理想情况是第 2 块距离接近 0 且排第一。


if __name__ == "__main__":
    # 做什么：只有「直接运行本文件」时才执行下面这行；被别的文件 import 时不自动跑。
    # 为什么：否则 check_env.py 或别处 import 一下就偷偷建库、花 API 额度。

    main()
