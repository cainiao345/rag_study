# ============================================================================
# 流水线 ①：解析 —— 一份资料 → 「一页一条」的列表
# ============================================================================
def load_pages(path):
    # 【目标】把一份 txt/pdf 读成一页一条记录，每条是带标签的字典。
    # 【输入】path = 一个资料文件的路径
    # 【输出】pages = [{"text": 正文, "page": 页码, "source": 文件名}, ...]
    # 【为什么非得按页读】页码只能在「还知道出处」的时候留住；
    #   若先把全文揉成一大坨字符串再切块，第 7 课的答案溯源就彻底没戏了。

    p = Path(path)
    # 做什么：把传进来的路径包成 Path 对象。
    # 为什么：下面要用 p.suffix 判断格式、p.name 取文件名。

    if p.suffix == ".txt":
        # 做什么：判断后缀是不是 .txt（.suffix 取出来的含点，如 ".txt"）。
        # 为什么：txt 是纯文本可以直接读，pdf 是二进制必须换解析库，两条路不一样。

        raw = p.read_text(encoding="utf-8")
        # 做什么：一次读完整个 txt 成一个字符串。
        # 为什么：必须显式写 utf-8，否则中文 Windows 默认 GBK 会乱码。

        parts = raw.split("\f")
        # 做什么：用换页符 "\f" 把全文切成「一页一段」。
        # 为什么：教学示例 txt 用它模拟 3 页，好让溯源能报出「第 2 页」；
        #         真实 txt 没有换页符时 split 只返回 1 段，整篇算第 1 页，不会报错。

    elif p.suffix == ".pdf":
        # 做什么：后缀是 .pdf 就走 PDF 分支。

        doc = pymupdf.open(str(p))
        # 做什么：打开 PDF，doc 相当于「整本书」。
        # 为什么：str(p) 把 Path 转成字符串，兼容这个库的参数要求。

        parts = [page.get_text() for page in doc]
        # 做什么：列表推导式，一页一页抽文字，得到「每页一段」的列表。
        # 为什么：写法等价于 for 循环 + append，但一行就能看清「每页 → 一段」的映射。

    else:
        # 做什么：其他后缀（docx、xlsx…）本讲暂不支持。

        raise ValueError(f"不支持的格式：{p.suffix}")
        # 做什么：主动抛异常让程序立刻停下，并在报错里带上实际后缀。
        # 为什么：悄悄返回空列表会让后面「解析出 0 块」，排查起来难得多；早失败早修。

    pages = []
    # 做什么：造空列表，装「一页一条」的记录。
    # 为什么：最终结果要按页顺序排列，所以用有序的列表。

    for i, text in enumerate(parts, start=1):
        # 做什么：一边遍历一边自动编号，start=1 让页码从 1 开始。
        # 为什么：enumerate 拆包后，第一个位置 i 接编号、第二个位置 text 接这一页文字，
        #         位置不能反（第 8 课抠过）；手写 i = i + 1 容易漏加或错位。

        clean = text.strip()
        # 做什么：去掉这一页首尾的空格和换行。
        # 为什么：空白页、页尾空行不该进库，否则检索会命中一堆没内容的块。

        if not clean:
            # 做什么：判断这一页是不是空字符串（空字符串在 Python 里算「假」）。

            continue
            # 做什么：跳过本轮，直接看下一页。
            # 为什么：注意「跳过的是页面」，但 i 是 enumerate 给的，不会因为跳过而断号。

        pages.append({
            # 做什么：往列表末尾塞一条记录（一个字典 = 带标签的一条数据）。
            # 为什么：字典比「三个平行列表」好——标签写在那儿，取用时不会记错位置。
            "text": clean,
            # 做什么：存这一页的正文（后面切块用）。
            "page": i,
            # 做什么：存页码（后面写出处卡片用）。
            "source": p.name,
            # 做什么：只存文件名（如 示例研报.txt），甩掉前面一长串目录。
            # 为什么：给用户看的出处不该是 D:/lw/... 这种绝对路径。
        })

    return pages
    # 做什么：把装满记录的列表交出去。


# ============================================================================
# 流水线 ② 的零件：按句子边界切块，不把一句话拦腰斩断
# ============================================================================
def chunk_by_sentence(text, max_size=CHUNK_SIZE):
    # 【目标】把一页长文字切成若干「不超过 max_size 字」的块，且尽量在句号处断开。
    # 【输入】text = 一页正文；max_size = 每块字数上限（默认 300）
    # 【输出】chunks = 块列表，每个元素是一段字符串
    # 【为什么不能按字数硬切】第 8 课实跑过：固定字数硬切会把 "14.3%" 切成 "14" + ".3%"，
    #   语义断了，检索与答案一起坏；按句切是成本最低的修法。

    normalized = text.replace("。", "。\n").replace("！", "！\n").replace("？", "？\n")
    # 做什么：在每个句末标点后面补一个换行，等于「在句子结束处画一道线」。
    # 为什么：三次连续写是链式调用——前一次 replace 的结果交给后一次继续替换；
    #         这样后面只要按 "\n" 切，就自然得到一句句完整的话。

    sentences = [s.strip() for s in normalized.split("\n") if s.strip()]
    # 做什么：split("\n") 按换行切成一句句，列表推导式顺手 strip 清洗 + 过滤空行。
    # 为什么：一行里同时做「切、洗、滤」，避免后面循环里到处写 if 判空。

    chunks = []
    # 做什么：空列表，装最终切好的块。

    buf = ""
    # 做什么：buf 是「暂存区」：先往里攒句子，攒够了才倒进 chunks。
    # 为什么：不到上限就继续拼，才不会切出一堆几十字的小碎片。

    for s in sentences:
        # 做什么：一句一句处理。

        if len(buf) + len(s) > max_size and buf:
            # 做什么：判断「加上这句就超上限」，且 buf 里确实已有内容。
            # 为什么：and buf 这个条件不能少——buf 为空时本来就该收下这句，
            #         否则遇到一个超长句会先 append 一个空块。

            chunks.append(buf)
            # 做什么：把攒好的整块存进列表。

            buf = s
            # 做什么：暂存区清空，改放当前这句（它属于下一块）。
            # 为什么：这句还没被存过，直接覆盖会丢，所以要先放进新的 buf。

        else:
            # 做什么：还没攒够（或 buf 为空）。

            buf = buf + s if buf else s
            # 做什么：buf 非空就拼在后面，为空就直接放第一句。
            # 为什么：条件表达式省掉一个 if；不加判断会在开头多出一个分隔符。

    if buf:
        # 做什么：循环结束后，暂存区可能还剩最后几句没倒出来。

        chunks.append(buf)
        # 做什么：补存一次。
        # 为什么：少了这步，每页结尾的尾巴会整段丢失（典型的 off-by-one 漏尾）。

    return chunks
    # 做什么：返回块列表。


# ============================================================================
# 流水线 ②：分块 + 配出处卡片
# ============================================================================
def chunk_pages(pages):
    # 【目标】把「一页一条」变成「一块一条」，并给每块配一张出处卡片（第 7 课）。
    # 【输入】pages = load_pages() 的输出
    # 【输出】chunks（原文块列表）, metas（出处卡片列表）——一次返回两个值
    # 【最重要的约束】chunks[i] 和 metas[i] 必须属于同一块，位置永远不能错开。
    # 【为什么用两个平行列表】Chroma 的 col.add 就要求 documents / metadatas
    #   分开传、按位置配对；这里提前按同样的顺序攒好，是最省事的对齐方式。

    chunks = []
    # 做什么：空列表，装原文块。
    metas = []
    # 做什么：空列表，装出处卡片。
    # 为什么：刻意和 chunks 分开攒，就是为了跟 col.add 的四列一一对应。

    for p in pages:
        # 做什么：一页一页处理。

        for c in chunk_by_sentence(p["text"]):
            # 做什么：对这一页按句切块，c 是切出来的一个块。
            # 为什么：字典取值 p["text"] 拿正文；页码 p["page"] 稍后写进卡片。

            chunks.append(c)
            # 做什么：原文塞进 chunks。

            metas.append({
                # 做什么：在「同一个循环、同一个 c」里立刻塞对应的卡片。
                # 为什么：这是全课的对齐关键——第 n 块 ↔ 第 n 张卡天然成立；
                #         若分两个循环各攒一次，只要哪次跳过一块就会全体串位。
                "source": p["source"],
                # 做什么：记下来自哪个文件。
                "page": p["page"],
                # 做什么：记下第几页（溯源就是靠它，绝不让模型自己编页码）。
            })

    return chunks, metas
    # 做什么：一次返回两个值。
    # 为什么：接收时写 chunks, metas = chunk_pages(pages)，Python 会自动拆包（元组解包）。


