#
# 【全篇最要命的两处 · 下面用专门的分节讲透】
#   A. embed_batch 里的 slots[item.index] = item.embedding：
#      API 批量返回可能乱序，必须按编号回填，否则「原文 ↔ 向量」错位，
#      不报错、日志全绿，只有问答时答案张冠李戴（静默错误）。
#   B. build_index 里的「长度校验 + 删旧集合」：
#      前者防四列错位，后者保证脚本重复跑的幂等性。
#
# 【注释约定】每个函数开头写「目标 / 输入 / 输出 / 为什么」；
#   每行代码上方写「做什么」+「为什么」，不写「定义一个函数」这种等于没说的废话。
# ============================================================================

