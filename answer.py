# ============================================================================
# answer.py —— 研报问答库的「问答侧」：用户提问 → 出答案 + 出出处
#
# 【这张脚本到底要干什么 · 一句话】
#   把用户的问题变成向量 → 去 chroma_db/ 里翻出最像的几块真料 →
#   连真料带「只准照着说」的规矩一起交给 DeepSeek → 模型答完，
#   再由程序把「出自哪份文件第几页」贴在答案后面。
#
# 【流水线地图 · 4 步，下面每个函数只是其中一步】
#   ① 向量化 embed_question()：问题文字 → 1 条 1024 维向量（复用建库那套）
#   ② 检索   retrieve()      ：向量 → top-k 原文 + 出处卡 + 距离
#   ③ 生成   make_prompt() → generate()：真料 + 防编造规矩 → DeepSeek 答案
#   ④ 溯源   format_sources()：出处由程序拼，绝不让模型自己写
#   rag_answer() = 把 ①~④ 串起来的总装线；main() 只管收问题 + 打印结果。
#
# 【全篇最要命的三处 · 都是「不报错但答案全错」的静默错误】
#   A. 问题向量必须和资料向量用「同一个 EMBED_MODEL、同一个 embed_client」。
#      换模型/换服务 → 两套坐标系，top-k 全是噪声，程序一路绿灯。
#   B. prompt 里的「严禁编造」四句少一句，模型就拿训练记忆糊弄，
#      链路全通、答案全编，第 6 课说过 RAG 等于白做。
#   C. 出处必须程序拼。让模型写页码，它会编一个很像的假页码（第 7 课）。
#      另外：库不存在时用 get_collection 明确报错，别 get_or_create 悄悄建个空库，
#      否则每次都答「资料中未提及」还查不出原因。
#
# 【注释约定】每个函数开头写「目标 / 输入 / 输出 / 为什么」；
#   每行代码上方写「做什么」+「为什么」，不写「定义函数」这种等于没说的废话。
# ============================================================================

