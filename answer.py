    # 做什么：把钥匙和地址装进客户端，交回调用者。
    # 为什么：等号左右是「关键字参数」；base_url 不改就发去 OpenAI 官网了。


# ============================================================================
# 流水线 ①：问题向量化 —— 和建库共用同一把「尺子」
# ============================================================================
def embed_question(question, embed_client):
    # 【目标】把一句问题变成 1024 维向量。
    # 【输入】question = 问题字符串；embed_client = 向量化专用客户端
    # 【输出】一条向量（数字列表）
    # 【为什么复用 embed_batch】它是（中）讲写的批量函数，内部按 item.index 保序、
    #   用的是同一个 EMBED_MODEL；只传 1 条也照常工作，还顺便保证提问不换尺子。

    return embed_batch([question], embed_client)[0]
    # 做什么：把问题包成「只有一个元素的列表」送进去，再取第 0 条结果。
    # 为什么：embed_batch 的接口收的是列表、回的也是列表；
    #         外面这层 [] 不能省，[0] 也不能省（省了会把「装着向量的列表」当向量用）。


# ============================================================================
# 流水线 ②：检索 —— 连书带借书卡一起取回来
# ============================================================================
def retrieve(col, q_vec, k=DEFAULT_K):
    # 【目标】查出最像问题的 k 块资料，并把出处卡、距离一起带回来。
    # 【输入】col = Chroma 集合；q_vec = 问题向量；k = 取几块
    # 【输出】hits = [{"text","source","page","distance"}, ...]
    # 【为什么必须连卡一起取】第 7 课：出处卡入库时不取回来，答案就没法溯源；
    #   include 少写 metadatas 不会报错，只是悄悄没有出处 —— 又是静默错误。

    res = col.query(
        # 做什么：向向量库发起一次「按向量找邻居」的查询。
        # 为什么：检索走的是向量，不是关键词；传 query_texts 会要求另配 embedding_function。

        query_embeddings=[q_vec],
        # 做什么：把问题向量包成列表传进去。
        # 为什么：Chroma 设计成能一次查多个问题，单问题也要套一层 []（和 ① 同理）。

        n_results=k,
        # 做什么：只要最像的 k 块。
        # 为什么：全给会稀释信号 + 撑爆 prompt；k 由 DEFAULT_K 统一控制。

        include=["documents", "metadatas", "distances"],
        # 做什么：显式点名要哪三列回来。
        # 为什么：默认不给齐；漏 metadatas 就没出处、漏 distances 就看不到「像不像」，
        #         而且漏了不报错，只会在后面变成「出处是 None」这种怪答案。
    )

    docs = res["documents"][0]
    # 做什么：取回原文列表。
    # 为什么：res["documents"] 是「list of lists」（外层对应每个问题），
    #         我们只问了一个问题，所以取 [0]；漏 [0] 会拿成二维列表，后面 zip 全错层。

    metas = res["metadatas"][0]
    # 做什么：取回出处卡列表（每张卡是 {"source": ..., "page": ...} 这样的字典）。
    # 为什么：溯源全靠它；同样要取 [0]。

    dists = res["distances"][0]
    # 做什么：取回距离列表。
    # 为什么：余弦集合下距离越小越像（0 = 一模一样），打印出来是「先看料」的排障依据。

    if not (len(docs) == len(metas) == len(dists)):
        # 做什么：进门先验票，三列必须一样长。
        # 为什么：下面靠位置配对，少一列就全体串位，原文配到别人的页码；
        #         这是（中）讲「四列对齐防呆」在问答侧的同一道保险。

        raise RuntimeError("检索结果三列长度不一致，可能是向量库损坏，请重建索引")
        # 做什么：红字停下，不给模型喂错料。
        # 为什么：宁可不答，也不能让模型拿着错料一本正经地编。

    hits = []
    # 做什么：准备一个空列表，装整理好的检索结果。
    # 为什么：对外统一成「字典列表」，后面拼 prompt 和拼出处都能用同一份数据。

    for text, meta, dist in zip(docs, metas, dists):
        # 做什么：三列并按位置拆包，一次拿到同一条记录的原文、卡片、距离。
        # 为什么这里可以用 zip（和上一讲「绝不用 zip」不矛盾）：
        #   上一讲三列是外部传进来的、可能不等长，zip 会静默截断；
        #   这里三列是同一次 query 返回的、长度天然一致，而且上面刚验过票。

        hits.append({
            # 做什么：把这一条记录整理成一张带标签的字典，追加进 hits。
            # 为什么：字典比「第 0 个是原文、第 1 个是页码」这类位置约定好读得多。

            "text": text,
            # 做什么：存原文，等会儿进 prompt 给模型看。
            "source": meta.get("source", "（出处未登记）"),
            # 做什么：取出处卡里的文件名，取不到就给个占位说明。
            # 为什么：用 .get() 而不是 meta["source"] —— 老库可能没写这个字段，
            #         直接中括号取会 KeyError，让整个问答崩在一张旧卡上。
            "page": meta.get("page", "?"),
            # 做什么：取页码，取不到写问号。
            # 为什么：宁可显示「?」也别让程序崩；同时提醒你该重建索引补页码。
            "distance": dist,
            # 做什么：把距离也带上。
            # 为什么：打印出来能肉眼判断「是不是压根没捞到相关料」（第 8 课排障心法）。
        })

    return hits
    # 做什么：把整理好的检索结果交回总装线。
    # 为什么：retrieve 只负责「取」，不负责「拼」和「问」，职责单一才好排查。


# ============================================================================
# 流水线 ③：拼 prompt + 调模型 —— 防编造是这一段的灵魂
# ============================================================================
def make_prompt(question, hits):
    # 【目标】把「真料 + 规矩 + 问题」拼成一段交给大模型的文本。
    # 【输入】question = 问题；hits = ② 检索回来的料
    # 【输出】prompt 字符串
    # 【为什么这段决定 RAG 成败】模型天生会用训练记忆答题；
    #   不写死「只准用【资料】」，链路全通但答案全编，第 6 课说这等于白做。

    blocks = []
    # 做什么：准备空列表，一块资料攒一个字符串。
    # 为什么：最后用 "\n\n---\n\n" 拼接，块与块之间要有看得见的分隔符（第 8 课）。

    for i, h in enumerate(hits, start=1):
        # 做什么：给每块资料自动编号 1、2、3…，同时取出该块字典。
        # 为什么：编号让模型能说「依据资料[2]」，也让人排障时对得上号；
        #         start=1 是给人看的编号，不是下标，别拿它去索引 hits。

        blocks.append(
            # 做什么：把「编号 + 出处 + 原文」拼成一块，追加进列表。
            f"[资料{i}] 来源：{h['source']} 第{h['page']}页\n{h['text']}"
            # 做什么：f-string 里的 {i} {h['source']} 会被替换成真实值。
            # 为什么：出处写在资料块里，模型才知道这话是谁说的；
            #         注意 f-string 外面用双引号，里面字典取值就用单引号，避免引号打架。
        )

    context = "\n\n---\n\n".join(blocks)
    # 做什么：用「空行 + 横线 + 空行」把资料块纵向摞成一篇。
    # 为什么：分隔符是结构信息不是装饰；黏成一坨时模型会分不清哪句属于哪块。

    prompt = f"""你是严谨的研报分析助手。请只根据下面【资料】回答问题。

规则：
1. 只使用【资料】里出现的信息，不得使用资料之外的记忆或常识。
2. 【资料】里没有的信息就回答「资料中未提及」，严禁编造数字、日期、公司名称。
3. 回答简短，必要时点明依据的是哪一条资料编号。
4. 不要自己写出处或页码，出处由程序统一附在答案后面。

【资料】
{context}

【问题】
{question}"""
    # 做什么：三引号 f-string，把 {context} 和 {question} 塞进一整段提示词。
    # 为什么：三引号能保留换行，模型才看得懂「资料区」和「问题区」是两块；
    #         第 4 条尤其关键 —— 让模型写页码 = 幻觉出处（第 7 课），必须提前堵死。

    return prompt
    # 做什么：把拼好的提示词交回总装线。
    # 为什么：make_prompt 不负责发请求，单独成函数才能打印出来检查「到底喂了什么料」。


def generate(prompt, chat_client):
    # 【目标】把提示词发给 DeepSeek，拿回答案文本。
    # 【输入】prompt = ③ 拼好的文本；chat_client = 只负责对话的客户端
    # 【输出】答案字符串
    # 【为什么和向量化分开】这一步走 DeepSeek，上一步走硅基流动，两把 key 不能混。

    r = chat_client.chat.completions.create(
        # 做什么：发起一次对话补全请求，返回响应对象。
        # 为什么：OpenAI 兼容接口统一叫 chat.completions.create；这里绝不能调 embeddings。

        model=CHAT_MODEL,
        # 做什么：指定用哪个模型写答案。
        # 为什么：和 EMBED_MODEL 完全无关，一个是写手、一个是尺子。

        messages=[
            # 做什么：传入「剧本」，两条消息组成一段对话。
            {"role": "system", "content": "你是严谨的研报分析助手，只依据给定资料作答。"},
            # 做什么：system 定角色和总基调，优先级高于用户消息。
            {"role": "user", "content": prompt},
            # 做什么：user 放真正的任务（资料 + 规矩 + 问题）。
            # 为什么：规矩写在 user 里再强调一遍，比只放 system 更不容易被忽略。
        ],
        temperature=0.1,
        # 做什么：把随机性压到很低。
        # 为什么：研报问答要稳定复现，别让同一问题两次答出不同数字。
    )

    return (r.choices[0].message.content or "").strip()
    # 做什么：从响应里挖出正文，去掉首尾空白后交回。
    # 为什么：r.choices 是列表（可能多个候选），取 [0] 才是第一条回复；
    #         content 偶尔是 None，用 `or ""` 兜住，避免 .strip() 抛 AttributeError。


# ============================================================================
# 流水线 ④：溯源 —— 出处由程序拼，一个字都不交给模型
# ============================================================================
def format_sources(hits):
    # 【目标】把检索到的资料整理成「【出处】[1] 文件 第N页…」的可读文本。
    # 【输入】hits = ② 的结果
    # 【输出】多行字符串
    # 【为什么不让模型写】模型会编一个很像的页码；溯源必须是「机器抄卡片」。

    lines = ["【出处】"]
    # 做什么：先放标题行，列表里每多一个元素就是将来的一行。
    # 为什么：最后用 "\n".join 纵向拼，比一路 += 字符串省事也更好读。

    seen = set()
    # 做什么：造一个空的集合，记哪些「文件+页码」已经列过。
    # 为什么：同一页被切成多块时，出处不该重复列三遍；set 自动去重、查找快。

    n = 0
    # 做什么：自己维护一个编号计数器。
    # 为什么：**不能用 enumerate** —— 遇到重复项 continue 跳过后，
    #         enumerate 的编号会断号（1、3、4），得自己数「真正列出来」的有几条。

    for h in hits:
        # 做什么：一条条看检索结果。
        # 为什么：只根据检索实际用到的料列出处，绝不把整库文件都列上。

        key = (h["source"], h["page"])
        # 做什么：用「文件名 + 页码」组成一个元组当去重键。
        # 为什么：单看文件名会把同文件不同页误判成重复；元组能一起装两个值，
        #         且元组不可变，才能放进 set（列表不行）。

        if key in seen:
            # 做什么：这一页已经列过，跳过。
            # 为什么：continue 直接进下一轮，后面的编号和 append 都不会执行。

            continue

        seen.add(key)
        # 做什么：把这一页登记为「已列过」。
        # 为什么：不登记，下一块同页资料又会重复输出一遍。

        n += 1
        # 做什么：真正要输出一行了，编号才加 1。
        # 为什么：这就是「自己维护 n」的意义：编号连续、和上面 prompt 的资料编号无关。

        lines.append(f"[{n}] {h['source']} 第{h['page']}页（距离 {h['distance']:.4f}）")
        # 做什么：拼出一行出处并追加。
        # 为什么：{h['distance']:.4f} 表示把距离格式化成 4 位小数，
        #         打印出来能顺手判断「这块到底像不像」；距离是距离不是相似度，越小越像。

    return "\n".join(lines)
    # 做什么：把标题行和所有出处行用换行符纵向拼成一个字符串。
    # 为什么：调用方可以直接 print，也可以塞进 API 返回体；返回字符串比直接 print 灵活。


# ============================================================================
# 总装线：把 ①~④ 串起来，对外只暴露这一个函数
# ============================================================================
def rag_answer(question, k=DEFAULT_K, embed_client=None, chat_client=None):
    # 【目标】问一句 → 给答案 + 出处 + 原始命中料（供排障）。
    # 【输入】question = 问题；k = 取几块；两个 client 可外部传入（方便测试时替换）
    # 【输出】(answer, sources, hits) 三件套
    # 【为什么要一次返回三样】答案给人看、出处给人查、hits 给第 8 课「先看料」排障用。

    q = (question or "").strip()
    # 做什么：把问题转成字符串并去掉首尾空白。
    # 为什么：`question or ""` 挡住 None（None.strip() 会 AttributeError），
    #         空问题不该白花一次 API 调用。

    if not q:
        # 做什么：空问题立刻停。
        # 为什么：不拦就会拿空字符串去向量化，检索出一堆噪声还照样扣额度。

        raise ValueError("问题不能为空")

    if embed_client is None:
        # 做什么：没传客户端就自己造一个。
        # 为什么：允许外部传是为了单测能塞假 client；默认让调用者一行就能用。

        embed_client = make_embed_client()
        # 做什么：造「只管向量化」的客户端（内部会跑 check_env 验两把 key）。
        # 为什么：复用（中）讲的函数，保证和建库走同一个服务、同一把 key。

    if chat_client is None:
        # 做什么：没传对话客户端就自己造。
        chat_client = make_chat_client()

    q_vec = embed_question(q, embed_client)
    # 做什么：流水线 ① 问题变向量。
    # 为什么：必须和库里资料用同一个 EMBED_MODEL，否则坐标系不同、检索全噪声。

    db = chromadb.PersistentClient(path=DB_PATH)
    # 做什么：打开磁盘上那个已经建好的向量库。
    # 为什么：问答侧只读不写；用和 build_index.py 完全相同的 DB_PATH 才找得到同一个库。

    try:
        col = db.get_collection(COLLECTION_NAME)
        # 做什么：按名字取已存在的集合。
        # 为什么：**故意不用 get_or_create_collection** —— 库没建时悄悄建个空集合，
        #         检索永远返回空、答案永远「资料中未提及」，还查不出原因（静默错误）。

    except NotFoundError:
        # 做什么：只接「集合不存在」这一种异常。
        # 为什么：磁盘坏、权限不足是别的问题，不能伪装成「请先建库」。

        raise RuntimeError("向量库还没有建立，请先运行 python build_index.py")
        # 做什么：给出一条能照着做的中文提示后终止。
        # 为什么：让使用者知道下一步该跑哪个脚本，而不是对着 404 发呆。

    hits = retrieve(col, q_vec, k=k)
    # 做什么：流水线 ② 取回 top-k 真料 + 出处卡 + 距离。
    # 为什么：RAG 的「R」就是这一步，拿不到料后面全是无米之炊。

    if not hits:
        # 做什么：一块料都没捞到，直接返回兜底话术。
        # 为什么：**不调模型** —— 空资料 + 问题发给模型 = 它用训练记忆硬编，
        #         还会白白扣一次生成费用；这是「没有就说没有」的兜底。

        return "资料库中未检索到相关内容，无法回答。", "【出处】\n（无）", []
        # 做什么：返回三件套，hits 给空列表保持形状一致。
        # 为什么：调用方永远能按同样的三个变量解包，不会一会儿 2 个一会儿 3 个。

    prompt = make_prompt(q, hits)
    # 做什么：流水线 ③ 前半：真料 + 防编造规矩拼成提示词。
    # 为什么：先拼好再发，出问题时可以 print(prompt) 看到底喂了什么。

    answer = generate(prompt, chat_client)
    # 做什么：流水线 ③ 后半：让 DeepSeek 基于真料写答案。
    # 为什么：模型只负责「组织语言」，事实必须来自【资料】。

    sources = format_sources(hits)
    # 做什么：流水线 ④ 程序拼出处。
    # 为什么：放在生成之后、由 Python 拼，模型没有任何机会伪造页码。

    return answer, sources, hits
    # 做什么：把三件套一次性交回调用者。
    # 为什么：一次返回多个值在 Python 里其实是打包成元组，调用方写三个变量即可拆开。


# ============================================================================
# main()：只管收问题 + 打印结果，不含任何业务逻辑
# ============================================================================
def main():
    # 【目标】命令行入口：python answer.py "你想问什么"。
    # 【输入】命令行参数（可省略）
    # 【输出】打印答案、出处、以及 top-k 命中概况
    # 【为什么把打印和业务分开】以后接网页/API 时直接调 rag_answer()，不用改这里。

    question = " ".join(sys.argv[1:]).strip()
    # 做什么：把命令行里第 1 个之后的所有参数用空格拼成一句问题。
    # 为什么：sys.argv[0] 是脚本名本身，不能算进问题；
    #         用 join 而不是只取 [1]，是因为中文问题常被空格拆成好几个参数。

    if not question:
        # 做什么：没给问题就用一个默认问题演示。
        # 为什么：让 `python answer.py` 直接能跑出效果，方便验收和教学。

        question = "2023 年经营活动现金流量净额是多少？同比增长多少？"
        # 做什么：默认问题特意挑示例研报第 2 页真有的数字。
        # 为什么：能一眼验出「检索有没有捞对页、模型有没有照着资料答」。

    answer, sources, hits = rag_answer(question)
    # 做什么：调总装线，把返回的元组拆成三个变量。
    # 为什么：拆包写法比 answer = result[0] 好读，也不容易取错下标。

    print(f"【问题】{question}")
    # 做什么：回显问题。
    # 为什么：日志里能确认「问的确实是这句」，避免参数被 shell 吃掉还不知道。

    print(f"【检索】命中 {len(hits)} 块：")
    # 做什么：打印命中块数。
    # 为什么：第 8 课「答不准先看料」，第一眼就该看到捞回几块。

    for i, h in enumerate(hits, start=1):
        # 做什么：逐块打印概况，自动编号。
        # 为什么：只打出处、距离、字数，不打全文 —— 全文太长会淹没日志，
        #         真要看料时再 print(h["text"]) 即可。

        print(f"  [{i}] {h['source']} 第{h['page']}页｜距离 {h['distance']:.4f}｜{len(h['text'])} 字")
        # 做什么：一行给出「哪份文件第几页、有多像、多长」。
        # 为什么：距离异常大（比如 >0.8）就说明资料可能压根不覆盖这个问题，该先补料。

    print(f"\n【答案】\n{answer}")
    # 做什么：空一行后打印模型答案。
    # 为什么：和检索日志视觉分开，截图给别看时一眼能找到答案。

    print(f"\n{sources}")
    # 做什么：最后打印程序拼好的出处。
    # 为什么：验收要求「注明答案出处（文档+页码）」，这一段就是交付证据。


if __name__ == "__main__":
    # 做什么：只有「直接运行本文件」时才执行 main()。
    # 为什么：以后别的文件 import answer.py 里的 rag_answer 时，
    #         不会莫名其妙自动问一个问题、白扣一次 API 费用。
    main()
